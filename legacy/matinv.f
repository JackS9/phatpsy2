      SUBROUTINE MATINV(A,N,B,M,DETERM)
C     F1 NBSB MATINV, DOUBLE PRECISION.
      IMPLICIT REAL*8(A-H,O-Z)
      DIMENSION IPIVOT(25),A(25,25),B(25,1),INDEX(25,2),PIVOT(25)
      EQUIVALENCE (IROW,JROW), (ICOLUM,JCOLUM), (AMAX,T,SWAP)
C
C     INITIALIZATION
C
   10 DETERM=1.D0
   15 DO 20 J=1,N
      IPIVOT(J)=0
   20 CONTINUE
   30 DO 550 I=1,N
C
C     SEARCH FOR PIVOT ELEMENT
C
   40 AMAX=0.D0
   45 DO 105 J=1,N
   50 IF (IPIVOT(J) .NE. 1) THEN
        DO 100 K=1,N
   70     IF (IPIVOT(K) .NE. 1) THEN
   80       IF (DABS(AMAX) .LT. DABS(A(J,K))) THEN
            IROW=J
            ICOLUM=K
            AMAX=A(J,K)
          END IF
        END IF
  100   CONTINUE
      END IF
  105 CONTINUE
  110 IPIVOT(ICOLUM)=IPIVOT(ICOLUM)+1
C
C     INTERCHANGE ROWS TO PUT PIVOT ELEMENT ON DIAGONAL
C
  130 IF (IROW .NE. ICOLUM) THEN
        DETERM=-DETERM
        DO 200 L=1,N
        SWAP=A(IROW,L)
        A(IROW,L)=A(ICOLUM,L)
        A(ICOLUM,L)=SWAP
  200 CONTINUE
        IF (M .GT. 0) THEN
          DO 250 L=1,M
          SWAP=B(IROW,L)
          B(IROW,L)=B(ICOLUM,L)
          B(ICOLUM,L)=SWAP
  250 CONTINUE
        END IF
      END IF
  260 INDEX(I,1)=IROW
  270 INDEX(I,2)=ICOLUM
  310 PIVOT(I)=A(ICOLUM,ICOLUM)
  320 DETERM=DETERM*PIVOT(I)
C
C      DIVIDE PIVOT ROW BY PIVOT ELEMENT
C
  330 A(ICOLUM,ICOLUM)=1.D0
  340 DO 350 L=1,N
      A(ICOLUM,L)=A(ICOLUM,L)/PIVOT(I)
  350 CONTINUE
  355 IF (M .GT. 0) THEN
        DO 370 L=1,M
        B(ICOLUM,L)=B(ICOLUM,L)/PIVOT(I)
  370 CONTINUE
      END IF
C
C     REDUCE NON-PIVOT ROWS
C
  380 DO 549 L1=1,N
  390 IF (L1 .NE. ICOLUM) THEN
        T=A(L1,ICOLUM)
        A(L1,ICOLUM)=0.D0
        DO 450 L=1,N
        A(L1,L)=A(L1,L)-A(ICOLUM,L)*T
  450 CONTINUE
        IF (M .GT. 0) THEN
          DO 500 L=1,M
          B(L1,L)=B(L1,L)-B(ICOLUM,L)*T
  500 CONTINUE
        END IF
      END IF
  549 CONTINUE
C
C     INTERCHANGE COLUMNS
C
  600 DO 710 II=1,N
  610 L=N+1-II
  620 IF (INDEX(L,1) .NE. INDEX(L,2)) THEN
        JROW=INDEX(L,1)
        JCOLUM=INDEX(L,2)
        DO 705 K=1,N
        SWAP=A(K,JROW)
        A(K,JROW)=A(K,JCOLUM)
        A(K,JCOLUM)=SWAP
  705 CONTINUE
      END IF
  710 CONTINUE
  550 CONTINUE
  740 RETURN
      END
