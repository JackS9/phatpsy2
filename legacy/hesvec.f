      SUBROUTINE HESVEC(H,N,NN,SCR,ROOT,ETA,SCRV,VEC,*)
      IMPLICIT REAL*8(A-H,O-Z)
      DIMENSION H(N,N),SCR(NN,NN),SCRV(NN),VEC(N)
      REAL*8 UNZ,TOL
C	  PARAMETER (UNZ = $F)
C	  PARAMETER (TOL = $3510000000000000)
	  PARAMETER (UNZ = 15)
	  PARAMETER (TOL = 16.0D0**(-12))
      FAC=ROOT+ETA
      ND=NN-1
      DO 5 II=NN,N
      VEC(II)=0.
    5 CONTINUE
      DO 12 II=1,NN
      DO 10 JJ=1,NN
      SCR(II,JJ)=H(II,JJ)
   10 CONTINUE
      SCR(II,II)=SCR(II,II)-FAC
   12 CONTINUE
      DO 35 II=1,ND
      IF (DABS(SCR(II,II)).LT.1.D0) GO TO 20
      SCR(II+1,II)=UNZ
      FAC=1.D0/SCR(II,II)
      GO TO 30
   20 DO 25 JJ=II,NN
      FAC=SCR(II,JJ)
      SCR(II,JJ)=SCR(II+1,JJ)
      SCR(II+1,JJ)=FAC
   25 CONTINUE
      FAC=SCR(II+1,II)
   30 DO 32 JJ=II,ND
      SCR(II+1,JJ+1)=SCR(II+1,JJ+1)-FAC*SCR(II,JJ+1)
   32 CONTINUE
      CONTINUE
   35 CONTINUE
      DO 45 JJ=1,NN
      SCRV(JJ)=1.D0
   45 CONTINUE
      NIT=0
   50 VEC(NN)=SCRV(NN)/SCR(NN,NN)
      AVC=VEC(NN)
      DO 60 III=1,ND
      NI=NN-III
      FAC=SCRV(NI)
      DO 55 JJ=NI,ND
      FAC=FAC-SCR(NI,JJ+1)*VEC(JJ+1)
   55 CONTINUE
      VEC(NI)=FAC/SCR(NI,NI)
   60 CONTINUE
      IF (DABS(AVC).LT.DABS(VEC(NI))) AVC =VEC(NI)
      IFLAG=0
      DO 65 JJ=1,NN
      VEC(JJ)=VEC(JJ)/AVC
      IF (DABS((VEC(JJ)-SCRV(JJ))/VEC(JJ)).GT.TOL) IFLAG=1
   65 CONTINUE
      IF (IFLAG.EQ.0) RETURN
      NIT=NIT+1
      IF (NIT.GT.8) RETURN 1
      DO 80 III=1,NN
      SCRV(III)=VEC(III)
   80 CONTINUE
      DO 90 III=1,ND
      IF (SCR(III+1,III).EQ.UNZ) GO TO 85
      FAC=SCRV(III+1)
      SCRV(III+1)=SCRV(III)-FAC*SCR(III+1,III)
      SCRV(III)=FAC
      GO TO 90
   85 SCRV(III+1)=SCRV(III+1)-SCRV(III)/SCR(III,III)
   90 CONTINUE
      GO TO 50
      END
